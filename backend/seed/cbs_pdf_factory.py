def generate_cbs_corpus_data(n: int = 100, seed: int = 42) -> list[tuple[SalarySlipData, dict]]:
    """Generate (slip, metadata_kwargs) tuples for the CBS reference corpus."""
    rng = random.Random(seed)
    results: list[tuple[SalarySlipData, dict]] = []
    base_date = datetime(2023, 9, 1, 9, 0, 0)

    for i in range(n):
        first = rng.choice(_CBS_FIRST_NAMES)
        last = rng.choice(_CBS_LAST_NAMES)
        bank_name, ifsc_prefix, producer, creator = rng.choice(_BANK_PROFILES)

        basic = rng.randrange(40000, 120000, 1000)
        hra = int(basic * rng.uniform(0.30, 0.45))
        da = int(basic * rng.uniform(0.10, 0.20))
        special = rng.randrange(5000, 20000, 500)
        gross = basic + hra + da + special
        pf = int(basic * 0.12)
        ptax = 200
        itax = int(gross * rng.uniform(0.10, 0.18))
        net = gross - pf - ptax - itax

        slip = SalarySlipData(
            employee_name=f"{first} {last}",
            employee_id=f"EMP{rng.randrange(10000, 99999)}",
            designation=rng.choice(_DESIGNATIONS),
            period="January 2024",
            branch_name=rng.choice(_BRANCH_NAMES),
            branch_ifsc=f"{ifsc_prefix}0{rng.randrange(100000, 999999)}",
            bank_name=bank_name,
            basic_pay=basic,
            hra=hra,
            da=da,
            special_allowance=special,
            pf_deduction=pf,
            professional_tax=ptax,
            income_tax=itax,
            net_pay=net,
            account_number=str(rng.randrange(10**11, 10**12)),
        )
        meta = {
            "producer": producer,
            "creator": creator,
            "creation_date": base_date + timedelta(days=rng.randint(0, 90),
                                                    hours=rng.randint(0, 8),
                                                    minutes=rng.randint(0, 59)),
        }
        results.append((slip, meta))

    return results


def make_cbs_pdf_bytes(slip: SalarySlipData, *, producer: str, creator: str,
                        creation_date: datetime) -> bytes:
    """One-shot: render + inject metadata. Returns final PDF bytes."""
    raw = build_cbs_pdf(slip)
    return inject_pdf_metadata(raw, producer=producer, creator=creator,
                                creation_date=creation_date)
